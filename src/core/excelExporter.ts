import * as XLSX from 'xlsx';
import { AuditedBIMElement, AuditSummary, BOQLineItem, KPISummary, ModelMetadata } from '../types/bim';

export class BOQExcelExporter {
  public exportToExcel(
    metadata: ModelMetadata,
    kpis: KPISummary,
    boq: BOQLineItem[],
    auditedElements: AuditedBIMElement[],
    auditSummary: AuditSummary
  ): void {
    const wb = XLSX.utils.book_new();

    // 1. Executive Summary Sheet
    const summaryData = [
      ['OpenBIM (IFC) AUTOMATED BILL OF QUANTITIES & AUDIT REPORT'],
      ['Generated by OpenBIM Cost Variance Intelligence Engine'],
      ['Standard: CPWD Delhi Schedule of Rates (DSR 2023)'],
      [''],
      ['PROJECT METADATA', ''],
      ['Project Name', metadata.project_name || 'L&T Commercial Complex - Block B'],
      ['Building Asset', metadata.building_name || 'Tower B Commercial Hub'],
      ['IFC Schema', metadata.schema || 'IFC4'],
      ['Total Structural Members', kpis.total_elements],
      [''],
      ['EXECUTIVE COST & QUANTITY KPIS', ''],
      ['Total Concrete Volume (m³)', kpis.total_concrete_cum],
      ['Total Concrete Cost (INR)', kpis.concrete_cost_inr],
      ['Total Reinforcement Steel (MT)', kpis.total_steel_tonne],
      ['Reinforcement Cost (INR)', kpis.steel_cost_inr],
      ['Overall Rebar Density (kg/m³)', kpis.rebar_density_overall],
      ['Total Shuttering Contact Area (m²)', kpis.total_formwork_sqm],
      ['Formwork Cost (INR)', kpis.formwork_cost_inr],
      ['TOTAL ESTIMATED STRUCTURAL BOQ (INR)', kpis.total_cost_inr],
      ['TOTAL BOQ (₹ LAKHS)', kpis.total_cost_lakhs],
      ['TOTAL BOQ (₹ CRORES)', kpis.total_cost_crores],
      [''],
      ['AI ANOMALY AUDIT PROFILE', ''],
      ['High-Risk Discrepancy Count', auditSummary.high_risk_count],
      ['Medium-Risk Warning Count', auditSummary.medium_risk_count],
      ['Compliant Elements Count', auditSummary.normal_count],
      ['At-Risk Cost Exposure (INR)', auditSummary.at_risk_cost_inr],
      ['At-Risk Cost Exposure (₹ Lakhs)', auditSummary.at_risk_cost_lakhs],
    ];
    const wsSummary = XLSX.utils.aoa_to_sheet(summaryData);
    XLSX.utils.book_append_sheet(wb, wsSummary, 'Executive Summary');

    // 2. Abstract BOQ Sheet
    const boqData = boq.map((item) => ({
      'Item Code': item['Item Code'],
      Category: item.Category,
      Description: item.Description,
      Unit: item.Unit,
      Quantity: item.Quantity,
      'Rate (INR)': item['Rate (INR)'],
      'Amount (INR)': item['Amount (INR)'],
      '% Share': item['% Share'],
    }));
    const wsBOQ = XLSX.utils.json_to_sheet(boqData);
    XLSX.utils.book_append_sheet(wb, wsBOQ, 'Abstract BOQ');

    // 3. Detailed M-Book (Measurement Book) Sheet
    const mbookData = auditedElements.map((el) => ({
      Tag: el.tag,
      'Element Name': el.name,
      Class: el.ifc_type.replace('Ifc', ''),
      Storey: el.storey,
      'Concrete Grade': el.concrete_grade,
      'Length (m)': el.length || el.bbox_dx || 0,
      'Width (m)': el.width || el.bbox_dy || 0,
      'Depth (m)': el.depth || el.bbox_dz || 0,
      'Net Vol (m³)': el.concrete_vol_cum,
      'Rebar (kg)': el.rebar_kg,
      'Formwork (m²)': el.formwork_sqm,
      'Concrete Cost (₹)': el.concrete_cost_inr,
      'Rebar Cost (₹)': el.rebar_cost_inr,
      'Formwork Cost (₹)': el.formwork_cost_inr,
      'Total Cost (₹)': el.total_cost_inr,
    }));
    const wsMBook = XLSX.utils.json_to_sheet(mbookData);
    XLSX.utils.book_append_sheet(wb, wsMBook, 'Detailed M-Book');

    // 4. Anomaly Audit Log Sheet
    const anomalyData = auditedElements
      .filter((el) => el.risk_level === 'HIGH' || el.risk_level === 'MEDIUM')
      .map((el) => ({
        Tag: el.tag,
        Name: el.name,
        Class: el.ifc_type,
        Storey: el.storey,
        'Risk Level': el.risk_level,
        'Net Vol (m³)': el.concrete_vol_cum,
        'Peer Mean Vol': el.cohort_mean_vol,
        'Volume Z-Score': el.z_score_vol,
        'Formwork Res (σ)': el.formwork_studentized_residual,
        'Rebar Res (σ)': el.rebar_studentized_residual,
        'Total Cost (₹)': el.total_cost_inr,
        'AI Diagnosis': el.anomaly_reasons,
        'Recommended Action': el.recommended_action,
      }));
    const wsAnomaly = XLSX.utils.json_to_sheet(anomalyData);
    XLSX.utils.book_append_sheet(wb, wsAnomaly, 'Anomaly Audit Log');

    const fileName = `OpenBIM_BOQ_${(metadata.project_name || 'Project').replace(/\s+/g, '_')}.xlsx`;
    XLSX.writeFile(wb, fileName);
  }

  public downloadCSV(content: string, fileName: string): void {
    const blob = new Blob([content], { type: 'text/csv;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.setAttribute('href', url);
    link.setAttribute('download', fileName);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  }

  public generateBOQCSV(boq: BOQLineItem[]): string {
    const headers = ['Item Code', 'Category', 'Description', 'Unit', 'Quantity', 'Rate (INR)', 'Amount (INR)', '% Share'];
    const rows = boq.map((b) => [
      `"${b['Item Code']}"`,
      `"${b.Category}"`,
      `"${b.Description.replace(/"/g, '""')}"`,
      `"${b.Unit}"`,
      b.Quantity,
      b['Rate (INR)'],
      b['Amount (INR)'],
      b['% Share'],
    ]);
    return [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
  }

  public generateAnomalyCSV(auditedElements: AuditedBIMElement[]): string {
    const anomalies = auditedElements.filter((el) => el.risk_level === 'HIGH' || el.risk_level === 'MEDIUM');
    const headers = [
      'Tag',
      'Name',
      'Class',
      'Storey',
      'Risk Level',
      'Net Vol (m3)',
      'Peer Mean (m3)',
      'Volume Z-Score',
      'Formwork Res (sigma)',
      'Rebar Res (sigma)',
      'Total Cost (INR)',
      'AI Diagnosis',
      'Recommended Action',
    ];
    const rows = anomalies.map((el) => [
      `"${el.tag}"`,
      `"${el.name}"`,
      `"${el.ifc_type}"`,
      `"${el.storey}"`,
      `"${el.risk_level}"`,
      el.concrete_vol_cum,
      el.cohort_mean_vol,
      el.z_score_vol,
      el.formwork_studentized_residual,
      el.rebar_studentized_residual,
      el.total_cost_inr,
      `"${el.anomaly_reasons.replace(/"/g, '""')}"`,
      `"${el.recommended_action.replace(/"/g, '""')}"`,
    ]);
    return [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
  }
}
